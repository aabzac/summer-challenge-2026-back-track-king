"""Compact spatial policy/value contract shared with btk.bot.neural.SpatialNet.

There are no game rules here: Java supplies features and every legal-action mask.
"""
from __future__ import annotations

import base64
from pathlib import Path
import numpy as np
import torch
from torch import nn

W, H, S, PLANES, TOWNS, TOWN_FEATURES = 30, 20, 600, 24, 12, 49
WEIGHT_COUNT = 3439
WEIGHT_ORDER = tuple(f"{name}.{part}" for name in (
    "stem", "town", "res1", "res2", "global_layer", "build", "ink", "stop", "noink", "value"
) for part in ("weight", "bias"))


def tensor_observations(observations):
    """Copy the exact Java observations, including conditional legal masks."""
    shapes = {"planes": (-1, PLANES, H, W), "towns": (-1, TOWNS, TOWN_FEATURES),
              "townCells": (-1, TOWNS), "regionIds": (-1, S), "scalars": (-1, 6),
              "buildMask": (-1, S + 1), "disruptMask": (-1, S + 1)}
    dtypes = {"townCells": np.int64, "regionIds": np.int64,
              "buildMask": np.bool_, "disruptMask": np.bool_}
    return {key: torch.from_numpy(np.asarray([o[key] for o in observations],
                                            dtype=dtypes.get(key, np.float32)).reshape(shape))
            for key, shape in shapes.items()}


def take_observations(observations, indices):
    return {key: value[indices] for key, value in observations.items()}


class SpatialNet(nn.Module):
    def __init__(self):
        super().__init__()
        self.stem = nn.Conv2d(PLANES, 8, 3, padding=1)
        self.town = nn.Linear(TOWN_FEATURES, 8)
        self.res1 = nn.Conv2d(8, 8, 3, padding=1)
        self.res2 = nn.Conv2d(8, 8, 3, padding=1)
        self.global_layer = nn.Linear(8, 8)
        self.build = nn.Linear(8, 1)
        self.ink = nn.Linear(8, 1)
        self.stop = nn.Linear(14, 1)
        self.noink = nn.Linear(14, 1)
        self.value = nn.Linear(14, 1)
        assert sum(p.numel() for p in self.parameters()) == WEIGHT_COUNT

    def forward(self, obs):
        n = obs["planes"].shape[0]
        valid = (obs["planes"][:, 0:1] > 0).to(torch.float32)
        denom = valid.sum((2, 3)).clamp_min(1)
        x = self.stem(obs["planes"]).relu().reshape(n, 8, S)
        town_valid = (obs["townCells"] >= 0).unsqueeze(1)
        town_features = self.town(obs["towns"]).transpose(1, 2) * town_valid
        town_indices = obs["townCells"].clamp_min(0).unsqueeze(1).expand(-1, 8, -1)
        x = x.scatter_add(2, town_indices, town_features).reshape(n, 8, H, W)
        x = (x + self.res2(self.res1(x).relu())).relu()
        global_features = (x * valid).sum((2, 3)) / denom
        x = (x + self.global_layer(global_features)[:, :, None, None]).relu()
        z = torch.cat(((x * valid).sum((2, 3)) / denom, obs["scalars"]), dim=1)
        cells = x.flatten(2).transpose(1, 2)
        build = torch.cat((self.build(cells).squeeze(-1), self.stop(z)), dim=1)
        cell_ink = self.ink(cells).squeeze(-1)
        region_valid = (obs["regionIds"] >= 0).to(torch.float32) * valid.flatten(1)
        region_indices = obs["regionIds"].clamp_min(0)
        sums = torch.zeros_like(cell_ink).scatter_add(1, region_indices, cell_ink * region_valid)
        counts = torch.zeros_like(cell_ink).scatter_add(1, region_indices, region_valid)
        ink = torch.cat((sums / counts.clamp_min(1), self.noink(z)), dim=1)
        return build, ink, self.value(z).squeeze(-1)

    def encoded_weights(self):
        state = self.state_dict()
        weights = np.concatenate([state[name].detach().cpu().numpy().ravel() for name in WEIGHT_ORDER])
        assert weights.size == WEIGHT_COUNT
        return base64.b64encode(weights.astype("<f4").tobytes()).decode("ascii")

    def export_java(self, path):
        payload = self.encoded_weights()
        source = ('package btk.bot.neural;\n\n'
                  '/** Generated by tools/spatial/train_spatial.py; do not edit weights manually. */\n'
                  'public final class SpatialWeights {\n'
                  '    private SpatialWeights() {}\n'
                  '    public static final String DATA =\n')
        chunks = [payload[i:i + 100] for i in range(0, len(payload), 100)]
        source += "\n".join('        "' + chunk + ('";' if i == len(chunks) - 1 else '" +')
                            for i, chunk in enumerate(chunks)) + "\n}\n"
        Path(path).parent.mkdir(parents=True, exist_ok=True)
        Path(path).write_text(source, encoding="utf-8")


def masked_distribution(logits, mask):
    if not mask.any(dim=-1).all():
        raise ValueError("Java supplied an empty legal mask")
    return torch.distributions.Categorical(logits=logits.masked_fill(~mask, -1e9))


def evaluate_plan(model, observations, actions):
    """Joint log probability is the sum over four conditional decisions.

    Rows are plan-major. Singleton masks after STOP have probability one and
    exactly zero policy gradient. Only stage zero supplies the critic value.
    """
    build, ink, values = model(observations)
    count = actions.shape[0]
    stage = torch.arange(count * 4) % 4
    logits = torch.where((stage == 3)[:, None], ink, build)
    masks = torch.where((stage == 3)[:, None], observations["disruptMask"], observations["buildMask"])
    dist = masked_distribution(logits, masks)
    logprob = dist.log_prob(actions.reshape(-1)).reshape(count, 4).sum(-1)
    entropy = dist.entropy().reshape(count, 4).sum(-1)
    return logprob, entropy, values.reshape(count, 4)[:, 0]
