WARM_START_SHA256 = "b8cdd34b01aac15c025bd36d41290fb261946debe483b3af268117ed7d8eca1d"
INITIAL_OPPONENT_SHA256 = "a60252899a6ebed8e599fc7ba9a22a53798bc38c1375329c4ecda81f25d96708"
POOL = ("spatial-ppo-v2-init", "spatial-ppo-v2-init", "spatial-ppo-v2", "spatial-ppo-v2",
        "v01", "v01", "v09", "v09")


def java_payload_hash(path):
    payload = "".join(re.findall(r'"([A-Za-z0-9+/=]+)"', Path(path).read_text(encoding="utf-8")))
    return hashlib.sha256(base64.b64decode(payload)).hexdigest()


def frozen_history_integrity():
    v1 = frozen_v1_integrity()
    path = ROOT / "docs/evidence/spatial-ppo-v2-training.json"
    v2 = json.loads(path.read_text(encoding="utf-8-sig"))
    for name, digest in v2["config"]["source_sha256"].items():
        if sha256(ROOT / name) != digest:
            raise AssertionError(f"Frozen v2 training source changed: {name}")
    if v2["final_weights_sha256"] != WARM_START_SHA256:
        raise AssertionError("Historical v2 evidence does not match the frozen warm start")
    generated = {}
    for name, expected in (("SpatialInitialWeights.java", INITIAL_OPPONENT_SHA256),
                           ("SpatialV2Weights.java", WARM_START_SHA256)):
        source = ROOT / "src/main/java/btk/bot/neural" / name
        if java_payload_hash(source) != expected:
            raise AssertionError(f"Frozen opponent weights changed: {name}")
        generated[name] = {"source_sha256": sha256(source), "payload_sha256": expected}
    return {"v1": v1, "v2_evidence_sha256": sha256(path),
            "v2_verified_source_count": len(v2["config"]["source_sha256"]), "generated_opponents": generated}


def v3_source_identities():
    sources = list((ROOT / "tools/spatial").glob("*.py"))
    sources += [path for path in (ROOT / "src/main/java/btk").rglob("*.java")
                if path.name != "SpatialV3Weights.java"]
    sources += [path for path in (ROOT / "src/main/resources/btk").rglob("*") if path.is_file()]
    return {str(path.relative_to(ROOT)).replace("\\", "/"): sha256(path) for path in sorted(set(sources))}


def v3_runtime_identities(command):
    identity = runtime_identities(command)
    classpath_at = command.index("-cp") if "-cp" in command else command.index("-classpath")
    files = []
    for item in command[classpath_at + 1].split(os.pathsep):
        path = Path(item)
        if path.is_dir():
            files.extend(p for p in (path / "btk").rglob("*") if p.is_file() and p.name != "SpatialV3Weights.class")
    if not any(path.name == "SpatialPoolBridge.class" for path in files):
        raise FileNotFoundError("Compiled SpatialPoolBridge identity missing")
    identity["compiled_engine_and_classpath_sha256"].update({str(path.resolve()): sha256(path) for path in sorted(set(files))})
    return identity


def export_v3_weights(model, path):
    path = Path(path)
    if path.name != "SpatialV3Weights.java":
        raise ValueError("V3 may generate only SpatialV3Weights.java")
    payload = model.encoded_weights()
    chunks = [payload[start:start + 100] for start in range(0, len(payload), 100)]
    source = ("package btk.bot.neural;\n\n"
              "/** Generated by tools/spatial/run_v3_training.py; do not edit weights manually. */\n"
              "public final class SpatialV3Weights {\n"
              "    private SpatialV3Weights() {}\n"
              "    public static final String DATA =\n")
    source += "\n".join('        "' + part + ('";' if i == len(chunks) - 1 else '" +')
                        for i, part in enumerate(chunks)) + "\n}\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source, encoding="utf-8")


class PoolAudit(GameAudit):
    def __init__(self, seed_start, environments, terminal_bonus=30., reward_scale=100., excluded_hashes=()):
        if environments != 8:
            raise ValueError("The fixed v3 pool requires eight environment slots")
        super().__init__(seed_start, environments, terminal_bonus, reward_scale, excluded_hashes)
        self.opponent_identities = {}
        self.opponent_failures = []
        self.opponent_calls = {spec: {"count": 0, "elapsed_ms": 0., "max_elapsed_ms": 0.} for spec in POOL}
        self.last_committed_turn = {}

    def observe_reply(self, message, reply):
        op = message.get("op", message.get("cmd"))
        if op == "opponentPlans":
            ids = message["envIds"]
            diagnostics = reply["diagnostics"]
            if len(diagnostics) != len(ids) or [d["envId"] for d in diagnostics] != ids:
                raise AssertionError("Opponent commitment batch/order mismatch")
            for diagnostic in diagnostics:
                env_id = diagnostic["envId"]
                current = self.current[env_id]
                key = (current["seed"], current["turn"])
                if (diagnostic["turn"] != current["turn"] or diagnostic["opponentSpec"] != POOL[env_id]
                        or diagnostic["learnerSeat"] != env_id % 2 or diagnostic["opponentSeat"] != 1 - env_id % 2
                        or diagnostic["budgetMs"] != 60000 or diagnostic["cached"]
                        or self.last_committed_turn.get(env_id) == key):
                    raise AssertionError("Opponent commitment identity, allowance or once-per-turn rule failed")
                self.last_committed_turn[env_id] = key
                stats = self.opponent_calls[POOL[env_id]]
                stats["count"] += 1
                stats["elapsed_ms"] += diagnostic["elapsedMs"]
                stats["max_elapsed_ms"] = max(stats["max_elapsed_ms"], diagnostic["elapsedMs"])
                if not diagnostic["complete"] or not diagnostic["legal"]:
                    self.opponent_failures.append({"seed": current["seed"], "mapSha256": current["mapSha256"], **diagnostic})
            if self.opponent_failures:
                raise AssertionError("Native opponent failed its frozen plan; diagnostics retained, no retry")
            return
        if op == "step":
            for env_id in message["envIds"]:
                current = self.current[env_id]
                if self.last_committed_turn.get(env_id) != (current["seed"], current["turn"]):
                    raise AssertionError("A learner transition lacks a pre-turn opponent commitment")
        if op in ("reset", "step"):
            for state in reply["envs"]:
                env_id = state["id"]
                if (not 0 <= env_id < 8 or state["learnerSeat"] != env_id % 2
                        or state["opponentSeat"] != 1 - env_id % 2 or state["opponentSpec"] != POOL[env_id]):
                    raise AssertionError("Fixed pool slot/seat identity changed")
                expected_weight = INITIAL_OPPONENT_SHA256 if env_id < 2 else WARM_START_SHA256 if env_id < 4 else None
                if state["opponentWeightsSha256"] != expected_weight:
                    raise AssertionError("Frozen opponent weight payload mismatch")
                identity = {key: state[key] for key in ("opponentSpec", "opponentParams", "opponentWeightsSha256")}
                prior = self.opponent_identities.get(POOL[env_id])
                if prior is not None and identity != prior:
                    raise AssertionError("Opponent parameters or weights changed")
                self.opponent_identities[POOL[env_id]] = identity
        super().observe_reply(message, reply)
        if op == "reset":
            offset = len(self.maps) - len(reply["envs"])
            for i, state in enumerate(reply["envs"]):
                self.current[state["id"]].update(learnerSeat=state["learnerSeat"], opponentSpec=state["opponentSpec"])
                self.maps[offset + i].update(
                    learnerSeat=state["learnerSeat"], opponentSpec=state["opponentSpec"])

    def capture(self, entry, seat, stage, obs):
        if seat == entry.get("learnerSeat"):
            super().capture(entry, seat, stage, obs)

    def summary(self):
        result = super().summary()
        requested = [(self.seed_start + env_id, turn, env_id % 2, stage) for env_id in (0, 1)
                     for turn in self.late_turns for stage in range(4)]
        result["late_panel_requested_slots"] = len(requested)
        result["late_panel_missing_slots"] = [list(key) for key in requested if key not in self.late_rows]
        result["opponent_identities"] = self.opponent_identities
        result["opponent_calls"] = self.opponent_calls
        result["opponent_failures"] = self.opponent_failures
        pools = {}
        for spec in dict.fromkeys(POOL):
            completed = [row for row in result["completed"] if row["opponentSpec"] == spec]
            unfinished = [row for row in result["unfinished"] if row["opponentSpec"] == spec]
            signs = [row["terminalSign"][row["learnerSeat"]] for row in completed]
            pools[spec] = {"environment_turns": sum(row["length"] for row in completed + unfinished),
                           "completed_games": len(completed), "learner_wins": signs.count(1),
                           "draws": signs.count(0), "learner_losses": signs.count(-1),
                           "completed_score_gap_sum": sum(row["score"][row["learnerSeat"]] - row["score"][1 - row["learnerSeat"]] for row in completed),
                           "unfinished_games": len(unfinished)}
        result["per_pool_training_outcomes"] = pools
        return result
