def weight_hash(model):
    return hashlib.sha256(base64.b64decode(model.encoded_weights())).hexdigest()


def export_java_class(model, path, class_name):
    if class_name not in ("SpatialInitialWeights", "SpatialV2Weights"):
        raise ValueError("Only the two v2 weight artifacts may be generated")
    payload = model.encoded_weights()
    chunks = [payload[start:start + 100] for start in range(0, len(payload), 100)]
    source = ("package btk.bot.neural;\n\n"
              "/** Generated by tools/spatial/run_v2_training.py; do not edit weights manually. */\n"
              f"public final class {class_name} {{\n"
              f"    private {class_name}() {{}}\n"
              "    public static final String DATA =\n")
    source += "\n".join('        "' + chunk + ('";' if i == len(chunks) - 1 else '" +')
                        for i, chunk in enumerate(chunks)) + "\n}\n"
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source, encoding="utf-8")


class TimedSpatialNet(SpatialNet):
    """Same network and state_dict; timers do not participate in learning."""
    def __init__(self):
        super().__init__()
        self.forward_seconds = 0.0
        self.forward_calls = 0
        self.forward_seconds_by_batch = {}

    def forward(self, obs):
        start = time.perf_counter()
        result = super().forward(obs)
        elapsed = time.perf_counter() - start
        self.forward_seconds += elapsed
        self.forward_calls += 1
        batch = int(obs["planes"].shape[0])
        self.forward_seconds_by_batch[batch] = self.forward_seconds_by_batch.get(batch, 0.0) + elapsed
        return result


class GameAudit:
    """Bind Java's terminal flags and scores to reset seeds; never resolve a game."""
    def __init__(self, seed_start, environments, terminal_bonus=30.0, reward_scale=100.0, excluded_hashes=()):
        self.seed_start = seed_start
        self.environments = environments
        self.terminal_bonus = terminal_bonus
        self.reward_scale = reward_scale
        self.next_seed = seed_start
        self.current = {}
        self.maps = []
        self.completed = []
        self.pending_terminal_ids = set()
        self.total_steps = 0
        self.resets = 0
        self.late_rows = {}
        self.late_turns = (63, 95)
        self.late_seeds = (seed_start, seed_start + 1)
        self.excluded_hashes = set(excluded_hashes)
        self.seen_hashes = set()

    def observe_reply(self, message, reply):
        op = message.get("op", message.get("cmd"))
        if op == "reset":
            for state, seed in zip(reply["envs"], message["seeds"], strict=True):
                if seed != self.next_seed:
                    raise AssertionError("Training reset seeds must be fresh and sequential")
                self.next_seed += 1
                env_id = state["id"]
                if env_id in self.current:
                    if env_id not in self.pending_terminal_ids:
                        raise AssertionError("A nonterminal episode was replaced")
                    self.pending_terminal_ids.remove(env_id)
                    self.resets += 1
                if state["turn"] != 0 or state["done"]:
                    raise AssertionError("Reset must return a nonterminal turn zero")
                if state.get("seed", seed) != seed:
                    raise AssertionError("Java returned a mismatched map seed")
                map_hash = state["mapSha256"]
                if map_hash in self.excluded_hashes or map_hash in self.seen_hashes:
                    raise AssertionError(f"Training map overlap at seed {seed}: {map_hash}; no replacement allowed")
                self.seen_hashes.add(map_hash)
                entry = {"id": env_id, "seed": seed, "mapSha256": state["mapSha256"],
                         "width": state["width"], "height": state["height"],
                         "turn": 0, "length": 0, "normalized_return": [0.0, 0.0],
                         "score": list(state["score"]), "done": False, "terminalSign": [0, 0]}
                self.current[env_id] = entry
                self.maps.append({key: entry[key] for key in ("id", "seed", "mapSha256", "width", "height")})
        elif op == "step":
            for state in reply["envs"]:
                env_id = state["id"]
                if env_id in self.pending_terminal_ids:
                    raise AssertionError("A terminal episode was stepped without resetting")
                entry = self.current[env_id]
                if state["turn"] != entry["turn"] + 1 or state["mapSha256"] != entry["mapSha256"]:
                    raise AssertionError("Java episode turn or map binding changed unexpectedly")
                entry["turn"] = state["turn"]
                entry["length"] += 1
                entry["score"] = list(state["score"])
                entry["done"] = bool(state["done"])
                entry["terminalSign"] = list(state["terminalSign"])
                self.total_steps += 1
                for seat in (0, 1):
                    entry["normalized_return"][seat] += (
                        state["rewardGap"][seat] + self.terminal_bonus * state["terminalSign"][seat]
                    ) / self.reward_scale
                if state["done"]:
                    record = {**entry, "normalized_return": list(entry["normalized_return"]),
                              "last_reward_gap": list(state["rewardGap"])}
                    self.completed.append(record)
                    self.pending_terminal_ids.add(env_id)
                else:
                    for seat, obs in enumerate(state["obs"]):
                        self.capture(entry, seat, 0, obs)
        elif op == "observe":
            for env_id, seat, stage, obs in zip(message["envIds"], message["seats"],
                                               message["stages"], reply["obs"], strict=True):
                self.capture(self.current[env_id], seat, stage, obs)

    def capture(self, entry, seat, stage, obs):
        if entry["seed"] in self.late_seeds and entry["turn"] in self.late_turns:
            key = (entry["seed"], entry["turn"], seat, stage)
            if key not in self.late_rows:
                self.late_rows[key] = {"seed": entry["seed"], "mapSha256": entry["mapSha256"],
                                       "turn": entry["turn"], "seat": seat, "stage": stage,
                                       "observation": obs}

    def summary(self):
        unfinished = [{**entry, "normalized_return": list(entry["normalized_return"])}
                      for env_id, entry in sorted(self.current.items()) if env_id not in self.pending_terminal_ids]
        completed_length = sum(row["length"] for row in self.completed)
        unfinished_length = sum(row["length"] for row in unfinished)
        if completed_length + unfinished_length != self.total_steps:
            raise AssertionError("Episode lengths do not cover every real engine transition")
        requested = [(seed, turn, seat, stage) for seed in self.late_seeds for turn in self.late_turns
                     for seat in (0, 1) for stage in range(4)]
        return {"completed_games": len(self.completed), "replacement_resets": self.resets,
                "completed_environment_turns": completed_length,
                "unfinished_environment_turns": unfinished_length, "environment_turns": self.total_steps,
                "pending_terminal_ids": sorted(self.pending_terminal_ids), "completed": self.completed,
                "unfinished": unfinished, "maps": self.maps, "next_map_seed": self.next_seed,
                "excluded_prior_map_hashes": len(self.excluded_hashes), "unique_training_map_hashes": len(self.seen_hashes),
                "late_panel_requested_slots": len(requested), "late_panel_captured_slots": len(self.late_rows),
                "late_panel_missing_slots": [list(key) for key in requested if key not in self.late_rows]}


class TimedBridge(Bridge):
    """Instrument transport; request-wait includes Java work and cannot separate it."""
    def __init__(self, command, audit):
        super().__init__(command)
        self.audit = audit
        self.timings = {key: 0.0 for key in ("encode_seconds", "write_seconds", "wait_read_seconds", "decode_seconds", "audit_seconds")}
        self.calls_by_op = {}

    def request(self, **message):
        if self.process.poll() is not None:
            raise RuntimeError(f"Java bridge exited with {self.process.returncode}")
        start = time.perf_counter()
        line = json.dumps(message, separators=(",", ":")) + "\n"
        encoded = time.perf_counter()
        self.process.stdin.write(line)
        self.process.stdin.flush()
        written = time.perf_counter()
        response = self.process.stdout.readline()
        received = time.perf_counter()
        if not response:
            raise RuntimeError("Java bridge closed stdout")
        reply = json.loads(response)
        decoded = time.perf_counter()
        if "error" in reply:
            raise RuntimeError(f"Java bridge: {reply['error']}")
        self.audit.observe_reply(message, reply)
        audited = time.perf_counter()
        for key, duration in (("encode_seconds", encoded - start), ("write_seconds", written - encoded),
                              ("wait_read_seconds", received - written), ("decode_seconds", decoded - received),
                              ("audit_seconds", audited - decoded)):
            self.timings[key] += duration
        self.calls += 1
        op = message.get("op", message.get("cmd"))
        self.calls_by_op[op] = self.calls_by_op.get(op, 0) + 1
        return reply
